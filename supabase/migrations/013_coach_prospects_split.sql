-- 013 · Fiches prospects : une ligne par fiche (nov. 2026)
--
-- Avant : toutes les fiches du Sales Coach dans la seule ligne `_coach_prospects`
-- de coach_store, réécrite en entier à chaque changement d'une fiche.
-- Après : table `coach_prospects` (une ligne par fiche). La ligne `_coach_prospects`
-- ne garde que les réglages (epoch…) et `split:true` ; sa date `updated_at` reste la
-- version de la liste (lue par les téléphones, jeton d'écriture conditionnelle).
--
-- À lancer APRÈS le déploiement des fonctions serveur (elles savent lire les deux
-- formats). Tout se fait dans une seule transaction : en cas d'erreur, rien ne change.
-- Relançable sans risque : la recopie n'a lieu que si la bascule n'est pas déjà faite.
-- ═══════════════════════════════════════════════════════════════════════════
BEGIN;

CREATE TABLE IF NOT EXISTS public.coach_prospects (
  id text PRIMARY KEY,
  ord bigint GENERATED BY DEFAULT AS IDENTITY,          -- ordre d'arrivée dans la liste
  data jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS coach_prospects_ord_idx ON public.coach_prospects (ord);
ALTER TABLE public.coach_prospects ENABLE ROW LEVEL SECURITY;      -- aucune policy : fonctions serveur uniquement
REVOKE ALL ON TABLE public.coach_prospects FROM PUBLIC, anon, authenticated;
GRANT ALL ON TABLE public.coach_prospects TO service_role;

-- Lecture : réglages + version + toutes les fiches, en une seule photo cohérente
CREATE OR REPLACE FUNCTION public.coach_prospects_read()
RETURNS jsonb LANGUAGE sql STABLE SECURITY INVOKER SET search_path = public AS $$
  SELECT jsonb_build_object(
    'updated_at', (SELECT updated_at FROM coach_store WHERE id = '_coach_prospects'),
    'meta', COALESCE((SELECT data - 'prospects' FROM coach_store WHERE id = '_coach_prospects'), '{}'::jsonb),
    'prospects', COALESCE((SELECT jsonb_agg(data ORDER BY ord) FROM coach_prospects), '[]'::jsonb)
  );
$$;

-- Écriture conditionnelle : n'applique les changements que si la version est encore celle lue.
-- Rend la nouvelle version, ou NULL si quelqu'un a écrit entre-temps (l'appelant relit et rejoue).
CREATE OR REPLACE FUNCTION public.coach_prospects_apply(p_token timestamptz, p_meta jsonb, p_upserts jsonb, p_deletes text[])
RETURNS timestamptz LANGUAGE plpgsql SECURITY INVOKER SET search_path = public AS $$
DECLARE
  cur timestamptz;
  nxt timestamptz;
BEGIN
  SELECT updated_at INTO cur FROM coach_store WHERE id = '_coach_prospects' FOR UPDATE;
  IF cur IS DISTINCT FROM p_token THEN RETURN NULL; END IF;
  -- Version à la milliseconde, toujours strictement supérieure à la précédente
  nxt := date_trunc('milliseconds', GREATEST(clock_timestamp(), COALESCE(cur, '-infinity'::timestamptz) + interval '1 millisecond'));
  IF p_deletes IS NOT NULL AND array_length(p_deletes, 1) > 0 THEN
    DELETE FROM coach_prospects WHERE id = ANY (p_deletes);
  END IF;
  INSERT INTO coach_prospects (id, data, updated_at)
    SELECT e->>'id', e, nxt
    FROM jsonb_array_elements(COALESCE(p_upserts, '[]'::jsonb)) e
    WHERE COALESCE(e->>'id', '') <> ''
  ON CONFLICT (id) DO UPDATE SET data = EXCLUDED.data, updated_at = EXCLUDED.updated_at;
  INSERT INTO coach_store (id, data, updated_at)
    VALUES ('_coach_prospects', (COALESCE(p_meta, '{}'::jsonb) - 'prospects') || '{"split":true}'::jsonb, nxt)
  ON CONFLICT (id) DO UPDATE SET data = EXCLUDED.data, updated_at = EXCLUDED.updated_at;
  RETURN nxt;
END;
$$;

REVOKE ALL ON FUNCTION public.coach_prospects_read() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.coach_prospects_apply(timestamptz, jsonb, jsonb, text[]) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.coach_prospects_read() TO service_role;
GRANT EXECUTE ON FUNCTION public.coach_prospects_apply(timestamptz, jsonb, jsonb, text[]) TO service_role;

-- Bascule des données (une seule fois) : sauvegarde complète, recopie fiche par fiche, puis la
-- ligne d'origine ne garde que les réglages. Le verrou bloque toute écriture pendant l'opération.
DO $$
DECLARE
  d jsonb;
  n_src int;
  n_dst int;
BEGIN
  SELECT data INTO d FROM coach_store WHERE id = '_coach_prospects' FOR UPDATE;
  IF d IS NULL THEN RAISE NOTICE 'Ligne _coach_prospects absente : rien à basculer'; RETURN; END IF;
  IF (d->>'split') = 'true' THEN RAISE NOTICE 'Bascule déjà faite : rien à faire'; RETURN; END IF;
  INSERT INTO coach_store (id, data, updated_at) VALUES ('_coach_prospects_avant_split', d, now())
    ON CONFLICT (id) DO UPDATE SET data = EXCLUDED.data, updated_at = EXCLUDED.updated_at;
  n_src := (SELECT count(DISTINCT e->>'id') FROM jsonb_array_elements(COALESCE(d->'prospects', '[]'::jsonb)) e WHERE COALESCE(e->>'id', '') <> '');
  DELETE FROM coach_prospects;
  INSERT INTO coach_prospects (id, data)
    SELECT DISTINCT ON (e->>'id') e->>'id', e
    FROM jsonb_array_elements(COALESCE(d->'prospects', '[]'::jsonb)) WITH ORDINALITY AS t(e, pos)
    WHERE COALESCE(e->>'id', '') <> ''
    ORDER BY e->>'id', pos DESC;
  -- Ordre d'arrivée d'origine
  UPDATE coach_prospects c SET ord = t.pos
    FROM (SELECT e->>'id' AS id, max(pos) AS pos FROM jsonb_array_elements(COALESCE(d->'prospects', '[]'::jsonb)) WITH ORDINALITY AS t(e, pos) GROUP BY 1) t
    WHERE c.id = t.id;
  PERFORM setval(pg_get_serial_sequence('public.coach_prospects', 'ord'), GREATEST((SELECT COALESCE(max(ord), 0) FROM coach_prospects), 1));
  n_dst := (SELECT count(*) FROM coach_prospects);
  IF n_dst <> n_src THEN RAISE EXCEPTION 'Bascule annulée : % fiches attendues, % recopiées', n_src, n_dst; END IF;
  UPDATE coach_store
    SET data = (d - 'prospects') || '{"split":true}'::jsonb,
        updated_at = date_trunc('milliseconds', GREATEST(clock_timestamp(), updated_at + interval '1 millisecond'))
    WHERE id = '_coach_prospects';
  RAISE NOTICE 'Bascule faite : % fiches, une ligne par fiche', n_dst;
END $$;

COMMIT;

